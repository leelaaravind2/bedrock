async function main() {
  let pass = true;
  const seen = new Map(); // digest → template (distinctness guard)
  process.stdout.write('=== UI==CLI byte-identity harness (A71-1) — engine: generator/dist ===\n');
  for (const c of CASES) {
    const choices = buildBlueprintChoices(c.sel);
    const files = await filesOf(choices);
    const digest = hashFiles(files);
    const nFiles = files.length;

    const eqChoices = deepEqual(choices, c.expectChoices);
    const filesOk = nFiles === c.expectFiles;
    let digestOk, ref;
    if (c.expectFull) { digestOk = digest === c.expectFull; ref = `== ${c.expectFull.slice(0, 12)} (full committed baseline${c.transcribedPrefix ? `; transcribed ${c.transcribedPrefix}` : ''})`; }
    else { digestOk = digest.startsWith(c.transcribedPrefix); ref = `startsWith ${c.transcribedPrefix} (transcribed)`; }

    const ok = eqChoices && filesOk && digestOk;
    if (!ok) pass = false;
    if (seen.has(digest)) { pass = false; process.stdout.write(`  FAIL DISTINCT ${c.key} shares digest with ${seen.get(digest)}\n`); }
    seen.set(digest, c.key);

    process.stdout.write(
      `  ${ok ? 'OK  ' : 'FAIL'} ${(c.anchor ? 'ANCHOR ' : 'free   ') + c.key.padEnd(12)} ` +
      `${nFiles}/${c.expectFiles} files · digest ${digest.slice(0, 12)} · ${ref}` +
      `${eqChoices ? '' : ' · CHOICES-DEEP-EQUAL FAIL'}${filesOk ? '' : ' · FILE-COUNT FAIL'}${digestOk ? '' : ' · DIGEST FAIL'}\n`);
    process.stdout.write(`       full: ${digest}\n`);
  }
  const distinct = seen.size === CASES.length;
  process.stdout.write(`\n  ${distinct ? 'OK  ' : 'FAIL'} five digests DISTINCT (${seen.size}/${CASES.length}) — identical digests would prove nothing\n`);
  process.stdout.write(`\nUI==CLI harness: ${pass ? 'PASS' : 'FAIL'}\n`);
  if (!pass) process.exit(1);
}
main().catch((e) => { process.stderr.write(String(e && e.stack ? e.stack : e) + '\n'); process.exit(1); });
